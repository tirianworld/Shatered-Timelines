export const formatDialogueText = (raw: string): string => {
  if (!raw) return '';
  return raw
    .replace(/\*.*?\*/g, '')
    .replace(/\(.*?\)/g, '')
    .replace(/\[.*?\]/g, '')
    .replace(/\s{2,}/g, ' ')
    .trim();
};

